/**
 * Portable standalone practice builder for binary-tree-level-order-traversal.
 *
 * Zero imports, zero DOM, zero network. Deterministic: the slug seed always
 * yields the same three variants. The judge contract is preserved exactly:
 *   signature levelOrder(TreeNode root) -> int[][]
 *   mode 'exact', literal-string args, examples == tests[0], 2 hints each.
 *
 * Independent oracle: level grouping is computed by recursive DFS-by-depth
 * (collect values per depth), which is structurally independent of the
 * walkthrough adapter's queue-size-snapshot BFS. Both agree on every test;
 * selfcheck.mjs cross-checks them plus a second iterative BFS.
 *
 * All drill inputs below are GENERATED by this file (seeded or fixed
 * boundary/adversarial fixtures). Official shard examples are NOT reused as
 * drill tests; they are only used in selfcheck to prove the oracle matches
 * the official contract.
 */

const SLUG = 'binary-tree-level-order-traversal'
const SEED_LABEL = 'level-order drills'

/* ------------------------------------------------------------- seeding -- */

function hashText(text) {
  const source = String(text)
  let hash = 2166136261 >>> 0
  for (let i = 0; i < source.length; i += 1) hash = Math.imul(hash ^ source.charCodeAt(i), 16777619) >>> 0
  return hash
}

function mulberry32(seed) {
  let a = seed >>> 0
  return function next() {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

function randInt(rng, lo, hi) {
  return lo + Math.floor(rng() * (hi - lo + 1))
}

function sampleRange(rng, count, lo, hi) {
  const pool = []
  for (let value = lo; value <= hi; value += 1) pool.push(value)
  for (let i = pool.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rng() * (i + 1))
    const swap = pool[i]
    pool[i] = pool[j]
    pool[j] = swap
  }
  return pool.slice(0, Math.min(count, pool.length))
}

/* ------------------------------------------------------------- literals -- */

function numLiteral(value) {
  const n = Number(value)
  if (!Number.isFinite(n)) return '0'
  return Number.isInteger(n) ? String(n) : String(Number(n.toFixed(6)))
}

function outLiteral(value) {
  if (value === null || value === undefined) return 'null'
  if (typeof value === 'boolean') return value ? 'true' : 'false'
  if (typeof value === 'number') return numLiteral(value)
  if (typeof value === 'string') return value
  if (Array.isArray(value)) return '[' + value.map(outLiteral).join(',') + ']'
  return String(value)
}

function inputLine(signature, args) {
  return signature.params.map((param, index) => `${(param && param.name) || 'arg' + index} = ${args[index]}`).join(', ')
}

/* ----------------------------------------------------- tree + oracles -- */

/** LeetCode compact level-order construction (shared input semantics). */
function buildTree(level) {
  if (!Array.isArray(level) || level.length === 0 || level[0] === null || level[0] === undefined) {
    return { root: null, nodes: [] }
  }
  let id = 0
  const root = { id: id++, value: level[0], left: null, right: null }
  const queue = [root]
  const nodes = [root]
  let cursor = 1
  for (let head = 0; head < queue.length && cursor < level.length; head += 1) {
    const parent = queue[head]
    for (const side of ['left', 'right']) {
      if (cursor >= level.length) break
      const v = level[cursor++]
      if (v === null || v === undefined) continue
      const child = { id: id++, value: v, left: null, right: null }
      parent[side] = child
      queue.push(child)
      nodes.push(child)
    }
  }
  return { root, nodes }
}

/**
 * PRIMARY oracle: recursive DFS-by-depth. Visits left subtree fully before
 * right, appending each value to its depth bucket. Independent of the
 * adapter's queue-size-snapshot BFS: different traversal order, no queue,
 * no size snapshot, same grouping result.
 */
export function oracleLevelOrderDFS(level) {
  const built = buildTree(level)
  if (built.root === null) return []
  const out = []
  ;(function dfs(node, depth) {
    if (node === null) return
    if (!out[depth]) out[depth] = []
    out[depth].push(node.value)
    dfs(node.left, depth + 1)
    dfs(node.right, depth + 1)
  })(built.root, 0)
  return out
}

/**
 * CROSS-CHECK oracle: iterative BFS with an explicit (node, depth) pair
 * queue — no size snapshot. Independent of BOTH the DFS oracle above and
 * the adapter's snapshot BFS; all three must agree.
 */
export function oracleLevelOrderPairs(level) {
  const built = buildTree(level)
  if (built.root === null) return []
  const out = []
  const queue = [{ node: built.root, depth: 0 }]
  for (let head = 0; head < queue.length; head += 1) {
    const { node, depth } = queue[head]
    if (!out[depth]) out[depth] = []
    out[depth].push(node.value)
    if (node.left !== null) queue.push({ node: node.left, depth: depth + 1 })
    if (node.right !== null) queue.push({ node: node.right, depth: depth + 1 })
  }
  return out
}

/* ----------------------------------------------------------- variants -- */

const SIGNATURE = Object.freeze({
  name: 'levelOrder',
  params: Object.freeze([{ name: 'root', type: 'TreeNode' }]),
  return: 'int[][]',
})

const INTENT_SAME = 'Same pattern, different numbers so you reproduce the reasoning.'
const INTENT_EDGE = 'Same pattern with the edge case the original hides.'
const INTENT_ADV = 'Same question with adversarial shapes that punish level-flattening shortcuts.'

function toTest(level) {
  const trimmed = level.slice()
  while (trimmed.length > 0 && (trimmed[trimmed.length - 1] === null || trimmed[trimmed.length - 1] === undefined)) trimmed.pop()
  return {
    args: [outLiteral(trimmed)],
    expected: outLiteral(oracleLevelOrderDFS(trimmed)),
  }
}

function buildVariant(spec) {
  const tests = spec.tests.slice(0, 5).map((test) => ({ args: test.args.map(String), expected: String(test.expected) }))
  const first = tests[0]
  return {
    id: spec.id,
    seedLabel: spec.seedLabel,
    intent: spec.intent,
    difficulty: spec.difficulty,
    title: spec.title,
    statement: spec.statement,
    signature: { name: SIGNATURE.name, params: SIGNATURE.params.map((p) => ({ ...p })), return: SIGNATURE.return },
    examples: [{ input: inputLine(SIGNATURE, first.args), output: first.expected, explain: '' }],
    tests,
    mode: 'exact',
    hints: spec.hints.slice(0, 2),
  }
}

function make(id, suffix, seedLabel, intent, statement, tests, hints, titleBase) {
  return buildVariant({
    id, seedLabel, intent, difficulty: 'Medium',
    title: titleBase + ' — ' + suffix + ' (level-group drill)',
    statement, tests, hints,
  })
}

/**
 * Build the three deterministic practice variants for one problem record.
 * Reads slug/title/difficulty only; the signature is asserted equal to the
 * official levelOrder(TreeNode)->int[][] contract. Returns [] when the
 * record is not this slug or the signature shape mismatches (never throws).
 */
export function buildLevelOrderVariants(problem) {
  try {
    if (!problem || problem.slug !== SLUG) return []
    const sig = problem.judge && problem.judge.signature
    if (!sig || sig.name !== 'levelOrder' || sig.return !== 'int[][]') return []
    if (!Array.isArray(sig.params) || sig.params.length !== 1 || sig.params[0].type !== 'TreeNode') return []
    const titleBase = String(problem.title || SLUG)
    const rng = mulberry32(hashText(SLUG))

    // v1: fresh seeded trees (generated values, never official examples).
    const v1 = []
    for (let n = 0; n < 4; n += 1) {
      const size = randInt(rng, 3, 7)
      const level = []
      for (let k = 0; k < size; k += 1) {
        if (k > 0 && rng() < 0.15) level.push(null)
        else level.push(randInt(rng, -9, 9))
      }
      if (level[0] === null || level[0] === undefined) level[0] = randInt(rng, -9, 9)
      v1.push(toTest(level))
    }

    // v2: fixed boundary fixtures (generated here; single-node uses 7 so the
    // value is not copied from the official [1] example; [] has one spelling).
    const v2 = [
      [],
      [7],
      [5, 4, null, 3, null, 2],
      [1, null, 2, null, 3],
      [1, 2, 3, 4, 5, 6, 7],
    ].map((level) => toTest(level))

    // v3: adversarial same-task shapes (no rule change: same signature,
    // same exact comparison; they punish queue-growth and value-equality bugs).
    const wide = sampleRange(rng, 15, -50, 50)
    const v3 = [
      [2, 2, 2, 2, 2],
      [1, null, 2, null, 3, null, 4],
      [1, 2, 3, null, null, 4, 5],
      wide,
    ].map((level) => toTest(level))

    return [
      make('v1', 'fresh trees', 'fresh trees', INTENT_SAME,
        'Given the root of a binary tree as a level-order array, return its values grouped by depth from left to right. Each inner array holds one level in encounter order. These fresh inputs use small seeded trees with values between -9 and 9. The signature and exact-match judge mode are unchanged.',
        v1,
        ['Snapshot the queue width before each round; nodes enqueued mid-round belong to the next level.', 'Append each visited value to the current level list, then push the finished level onto the result.'],
        titleBase),
      make('v2', 'edge cases', 'edge cases', INTENT_EDGE,
        'Same level-grouping task at the boundary shapes. Given the root as a level-order array, return one inner array per depth. Inputs include the empty tree, a single node, left-only and right-only chains with gaps, and a full balanced tree. Missing children never create placeholder entries in the output.',
        v2,
        ['An empty input yields zero levels, not one empty level — guard the null root first.', 'A null slot means no node there; skip it without emitting any placeholder value.'],
        titleBase),
      make('v3', 'adversarial shapes', 'adversarial shapes', INTENT_ADV,
        'Same question with adversarial shapes that punish level-flattening shortcuts. Given the root as a level-order array, return the values grouped by depth, left to right. Duplicate-heavy runs, deep right spines, interior gaps, and a 15-node balanced tree stress the snapshot-width discipline. No rule change: the signature and exact comparison are unchanged.',
        v3,
        ['Never let the queue grow inside the level loop; iterate exactly size times per round.', 'Duplicate values are fine — grouping is by depth position, never by value equality.'],
        titleBase),
    ]
  } catch {
    return []
  }
}

